def milliseconds_to_samples(milliseconds: int) -> int:
    return round(SAMPLE_RATE * milliseconds / 1000)


def tone_pcm(note: Note) -> list[int]:
    sample_count = milliseconds_to_samples(note.on_ms)
    fade_samples = min(milliseconds_to_samples(round(FADE_MS)), sample_count // 2)
    phase = 0.0
    step = note.hz / SAMPLE_RATE
    peak = round(32767 * AMPLITUDE)
    pcm: list[int] = []

    for index in range(sample_count):
        if fade_samples:
            attack = min(1.0, (index + 1) / fade_samples)
            release = min(1.0, (sample_count - index) / fade_samples)
            envelope = min(attack, release)
        else:
            envelope = 1.0
        value = peak if phase < 0.5 else -peak
        pcm.append(round(value * envelope))
        phase = (phase + step) % 1.0

    pcm.extend([0] * milliseconds_to_samples(note.gap_ms))
    return pcm


def melody_pcm(melody: Melody) -> list[int]:
    pcm: list[int] = []
    for note in melody.notes:
        pcm.extend(tone_pcm(note))
    return pcm


def write_wav(path: Path, pcm: list[int]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), "wb") as wav:
        wav.setnchannels(1)
        wav.setsampwidth(2)
        wav.setframerate(SAMPLE_RATE)
        wav.writeframes(struct.pack(f"<{len(pcm)}h", *pcm))


def write_c_tables(path: Path, melodies: tuple[Melody, ...] = MELODIES) -> None:
    lines = [
        "/* Generated by sound_design/generate_previews.py. */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "typedef struct {",
        "    uint16_t frequency_hz;",
        "    uint16_t on_ms;",
        "    uint16_t gap_ms;",
        "} buzzer_note_t;",
        "",
    ]
    for melody in melodies:
        lines.append(
            f"/* {melody.title}; {melody.duration_ms / 1000:.3f} s. */"
        )
        lines.append(f"static const buzzer_note_t k_sound_{melody.c_name}[] = {{")
        for note in melody.notes:
            lines.append(f"    {{{note.hz}, {note.on_ms}, {note.gap_ms}}},")
        lines.extend(("    {0, 0, 0},", "};", ""))
    path.write_text("\n".join(lines), encoding="utf-8", newline="\n")


def main() -> int:
    root = Path(__file__).resolve().parent
    preview_dir = root / "previews"
    combined: list[int] = []
    separator = [0] * milliseconds_to_samples(1500)

    for index, melody in enumerate(MELODIES):
        pcm = melody_pcm(melody)
        write_wav(preview_dir / melody.wav_name, pcm)
        if index:
            combined.extend(separator)
        combined.extend(pcm)
        print(
            f"{melody.wav_name}: {melody.duration_ms / 1000:.3f} s, "
            f"{len(melody.notes)} notes"
        )

    write_wav(preview_dir / "00_all_melodies_in_order.wav", combined)
    write_c_tables(root / "melody_tables.generated.h")
    print(f"Generated previews in {preview_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
