"""Generate square-wave WAV previews and C note tables for the MCL02M buzzer."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
import struct
import wave


SAMPLE_RATE = 44_100
AMPLITUDE = 0.22
FADE_MS = 2.5  # Preview-only edge smoothing; firmware still uses hard PWM edges.


@dataclass(frozen=True)
class Note:
    hz: int
    on_ms: int
    gap_ms: int = 0


@dataclass(frozen=True)
class Melody:
    c_name: str
    wav_name: str
    title: str
    purpose: str
    notes: tuple[Note, ...]

    @property
    def duration_ms(self) -> int:
        return sum(note.on_ms + note.gap_ms for note in self.notes)


